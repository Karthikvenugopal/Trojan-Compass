"""Compact model protocol, translated into strict domain contracts without inference.

Unanswered fields are absent rather than repeated as nullable nested objects. Every
emitted fact has one student quote. AI still owns semantics, questions and search.
"""

from typing import Literal

from pydantic import Field

from trojan_compass.assistant import RouteDecision
from trojan_compass.contracts import (
    ChatMessage,
    Clarification,
    Contract,
    InformationKey,
    RetrievalContext,
    Skill,
    StudentAnswer,
    StudentStatement,
    SupportedText,
    Target,
)
from trojan_compass.extraction import ExtractionFailure, quoted
from trojan_compass.failures import FailureReason


class StudentFact(Contract):
    field: str = Field(
        pattern=(
            r"^(interest|experience|completed_course|goal|program|study_stage|direction|"
            r"direction_detail|background|work_experience|completed_courses|time_window|"
            r"modality|preference|preferences|target\.(role|company|team)|target_company|skills\..{1,100})$"
        ),
        max_length=120,
    )
    status: Literal["provided", "unknown", "none", "known", "learning", "not_yet_learned"]
    # Always text on the wire, including 'unknown'/'none'. Non-provided text is
    # ignored; domain nulls are assembled by code instead of generated by a model.
    value: str = Field(min_length=1, max_length=1000)
    message_index: int = Field(ge=0, strict=True)
    quote: str = Field(min_length=1, max_length=4000)


class PlannerQuestion(Contract):
    field: InformationKey
    text: str = Field(min_length=1, max_length=1500)
    options: list[str] = Field(default_factory=list, max_length=6)
    reason: str = Field(min_length=1, max_length=300)


class PlannerOutput(Contract):
    intent: Literal["ask", "search", "campus_question", "course_question"]
    facts: list[StudentFact] = Field(default_factory=list, max_length=96)
    question: PlannerQuestion | None = None
    search_query: str = Field(default="", max_length=500)
    occupation_ids: list[str] = Field(default_factory=list, max_length=3)
    course_codes: list[str] = Field(default_factory=list, max_length=5)
    needs_library_hours: bool = False

    def context(self, messages: list[ChatMessage]) -> RetrievalContext:
        """Only representation changes: never infer mastery or fill missing facts."""
        context = RetrievalContext()
        company: StudentFact | None = None
        rows: list[tuple[StudentFact, StudentStatement]] = []
        for fact in self.facts:
            index = fact.message_index
            if not (
                index < len(messages)
                and messages[index].role == "user"
                and quoted(fact.quote, messages[index].content)
            ):
                matches = [
                    i
                    for i, message in enumerate(messages)
                    if message.role == "user" and quoted(fact.quote, message.content)
                ]
                if len(matches) != 1:
                    raise ExtractionFailure(FailureReason.EVIDENCE)
                index = matches[0]
            rows.append((fact, StudentStatement(message_index=index, quote=fact.quote)))
        scalars: dict[tuple[str, int], tuple[str, str]] = {}
        for fact, statement in sorted(rows, key=lambda row: row[1].message_index):
            field = fact.field.casefold()
            proof = [statement]
            if field not in {
                "interest",
                "experience",
                "completed_course",
                "goal",
                "preference",
                "preferences",
            }:
                scalar_key = (field, statement.message_index)
                scalar_value = (fact.status, fact.value)
                if scalar_key in scalars and scalars[scalar_key] != scalar_value:
                    raise ExtractionFailure(FailureReason.CONFLICT)
                scalars[scalar_key] = scalar_value
            supported = SupportedText(value=fact.value, evidence=proof)
            if field.startswith("skills."):
                status = fact.status
                if status in {"provided", "none"}:
                    status = (
                        "unknown"  # An ambiguous skill mention proves no mastery/lack of study.
                    )
                context.skills.append(
                    Skill.model_validate(
                        {
                            "name": field[7:],
                            "status": status,
                            "evidence": proof,
                        }
                    )
                )
                if fact.status == "unknown":
                    context.answers.append(
                        StudentAnswer(field=field, status="unknown", evidence=proof)
                    )
                continue
            if fact.status in {"unknown", "none"}:
                answer_field = {
                    "interest": "direction",
                    "experience": "work_experience",
                    "completed_course": "completed_courses",
                    "goal": "target",
                    "preference": "preferences",
                }.get(field, field)
                if answer_field.startswith("target."):
                    answer_field = "target"
                context.answers.append(
                    StudentAnswer.model_validate(
                        {
                            "field": answer_field,
                            "status": fact.status,
                            "evidence": proof,
                        }
                    )
                )
                continue
            if fact.status != "provided":
                raise ExtractionFailure(FailureReason.SCHEMA)
            if field == "interest":
                context.interests.append(supported)
            elif field == "experience":
                context.experiences.append(supported)
            elif field == "completed_course":
                context.completed_courses.append(supported)
            elif field == "goal":
                context.goals.append(supported)
            elif field in {"program", "study_stage"}:
                setattr(context, field, supported)
            elif field in {"time_window", "modality"}:
                setattr(context.constraints, field, supported)
            elif field in {"preference", "preferences"}:
                context.constraints.additional_preferences.append(supported)
            elif field.startswith("target."):
                context.target = Target.model_validate(
                    {"kind": field.split(".")[1], "name": fact.value, "evidence": proof}
                )
            elif field == "target_company":
                company = fact
            else:
                context.answers.append(
                    StudentAnswer(field=field, status="provided", value=fact.value, evidence=proof)
                )
        if company is not None:
            if context.target is None:
                raise ExtractionFailure(FailureReason.SCHEMA)
            context.target.company_name = company.value
            context.target.evidence.append(
                StudentStatement(message_index=company.message_index, quote=company.quote)
            )
        return context

    def clarification(self) -> Clarification | None:
        return (
            Clarification(
                text=self.question.text,
                options=self.question.options,
                requested_fields=[self.question.field],
                reason=self.question.reason,
            )
            if self.question
            else None
        )

    def route(self) -> RouteDecision | None:
        if self.intent not in {"campus_question", "course_question"}:
            return None
        return RouteDecision.model_validate(
            {
                "intent": self.intent,
                "search_query": self.search_query,
                "course_codes": self.course_codes,
                "needs_library_hours": self.needs_library_hours,
            }
        )


class QuestionReview(Contract):
    """Independent LLM semantic review; code applies only validated edit operations."""

    next_step: Literal["ask", "search"]
    add_facts: list[StudentFact] = Field(default_factory=list, max_length=96)
    remove_fact_indices: list[int] = Field(default_factory=list, max_length=96)
    question: PlannerQuestion | None = None
    search_query: str = Field(default="", max_length=500)
    occupation_ids: list[str] = Field(default_factory=list, max_length=3)


def apply_question_review(wire: PlannerOutput, review: QuestionReview) -> PlannerOutput:
    """Apply explicit model edits; never classify student language in Python."""
    removed = set(review.remove_fact_indices)
    if len(removed) != len(review.remove_fact_indices) or any(
        index < 0 or index >= len(wire.facts) for index in removed
    ):
        raise ExtractionFailure(FailureReason.EVIDENCE)
    facts = [fact for i, fact in enumerate(wire.facts) if i not in removed]
    facts.extend(review.add_facts)
    return PlannerOutput.model_validate(
        {
            "intent": review.next_step,
            "facts": [fact.model_dump() for fact in facts],
            "question": review.question.model_dump() if review.question else None,
            "search_query": review.search_query,
            "occupation_ids": review.occupation_ids,
        }
    )


